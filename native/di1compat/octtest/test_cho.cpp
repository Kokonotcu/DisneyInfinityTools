int testChoLayout(const Args& a)
{
    const Corpus A = choIndex(a.argv[2]), B = choIndex(a.argv[3]);
    Tally c;
    for (auto& [n, p] : A) {
        auto twin = B.find(n);
        if (twin == B.end()) continue;
        std::string b = slurp(p);
        if (!hasName(b, "LayoutPool")) continue;
        oct::File f = parse(b);
        std::string b3 = slurp(twin->second);
        oct::File g = parse(b3);
        cho::layout30(f);
        for (const char* k : {"PlacementNode", "InstanceNode", "Attachment"}) {
            bool ok = layoutDump(f, k) == layoutDump(g, k);
            ++c[std::string(k) + (ok ? " same" : " differ")];
            if (!ok && c[std::string(k) + " differ"] <= kShownLayoutDiffs) printf("differ %s %s\n", n.c_str(), k);
        }
    }
    printTally(c, 6);
    return 0;
}

