// 'name=values ' of one field record.
std::string fieldText(const oct::File& f, const oct::Rec& r)
{
    std::string s = f.name(r) + "=";
    if (oct::spec(r.type).kind == oct::NAME) {
        for (auto& v : f.nameValues(r)) s += v;
    } else {
        for (int32_t v : f.ints(r)) s += std::to_string(v);
    }
    return s + " ";
}

// "Kind{field=value ...}" per record named kind (PlacementNode, InstanceNode, Attachment).
std::vector<std::string> layoutDump(const oct::File& f, const char* kind)
{
    std::vector<std::string> out;
    for (size_t i = 0; i < f.recs.size(); ++i) {
        if (f.name(f.recs[i]) != kind) continue;
        std::string s = std::string(kind) + "{";
        for (size_t j = i + 1, e = f.blockEnd(i); j < e; ++j) s += fieldText(f, f.recs[j]);
        out.push_back(s + "}");
    }
    return out;
}

// ---- --cho-time ----

struct TimeTally {
    size_t same = 0, differ = 0, with = 0;   // with: had a time range
};
constexpr size_t kShownTimeDiffs = 5;

// Strips every SubNetwork's MinTime / MaxTime; true when there was one.
bool stripTimeRanges(oct::File& f)
{
    const size_t n0 = f.recs.size();
    bool inSn = false;
    for (size_t i = 0; i < f.recs.size();) {
        const oct::Rec& r = f.recs[i];
        if (r.level <= 2) inSn = r.level == 2 && f.name(r) == "SubNetwork";
        const bool range = f.name(r) == "MinTime" || f.name(r) == "MaxTime";
        if (inSn && r.level == 3 && range) f.recs.erase(f.recs.begin() + i);
        else ++i;
    }
    return f.recs.size() != n0;
}

// A shipped 3.0 file, time ranges stripped and regenerated by time30, must come back byte-identical.
void retimeCheck(const fs::path& p, TimeTally& t)
{
    std::string b = slurp(p);
    if (!hasName(b, "SubNetworkPool")) return;
    oct::File f = parse(b);
    if (stripTimeRanges(f)) ++t.with;
    cho::time30(f);
    if (f.write() == b) {
        ++t.same;
        return;
    }
    if (const size_t n = ++t.differ; n <= kShownTimeDiffs) printf("differ %s\n", p.string().c_str());
}

// ---- --cho-time10 ----

using TimeRanges = std::vector<std::pair<float, float>>;
struct Time10Tally {
    size_t same = 0, close = 0, differ = 0, none = 0;
};
constexpr double kRangeTolerance = 1e-4;   // time30's sums against the ranges 3.0 stores
constexpr size_t kShownTime10Diffs = 8;

// Each SubNetwork's MinTime..MaxTime in record order.
TimeRanges timeRanges(const oct::File& f)
{
    TimeRanges v;
    for (size_t i = 0; i < f.recs.size(); ++i) {
        const std::string& n = f.name(f.recs[i]);
        const bool range = n == "MinTime" || n == "MaxTime";
        if (f.recs[i].level != 3 || !range) continue;
        float x;
        memcpy(&x, f.recs[i].pay.data(), sizeof x);
        if (n == "MinTime") v.push_back({x, 0.f});
        else if (!v.empty()) v.back().second = x;
    }
    return v;
}

bool rangesNear(const TimeRanges& x, const TimeRanges& y)
{
    bool nearly = x.size() == y.size();
    for (size_t k = 0; nearly && k < x.size(); ++k)
        nearly = fabs(x[k].first - y[k].first) < kRangeTolerance && fabs(x[k].second - y[k].second) < kRangeTolerance;
    return nearly;
}

// time30 on one 1.0 twin: its ranges against the 3.0 twin's.
void time10Twin(const std::string& n, const fs::path& p10, const fs::path& p30, Time10Tally& t)
{
    std::string b = slurp(p10), b3 = slurp(p30);
    oct::File f = parse(b), g = parse(b3);
    cho::time30(f);
    auto x = timeRanges(f), y = timeRanges(g);
    if (x.empty() && y.empty()) {
        ++t.none;
        return;
    }
    const bool nearly = rangesNear(x, y);
    if (x == y) {
        ++t.same;
        return;
    }
    if (nearly) {
        ++t.close;
        return;
    }
    if (const size_t k = ++t.differ; k <= kShownTime10Diffs)
        printf("differ %s: %zu ranges vs %zu, first %g..%g vs %g..%g\n", n.c_str(), x.size(), y.size(),
               x.empty() ? 0 : x[0].first, x.empty() ? 0 : x[0].second, y.empty() ? 0 : y[0].first,
               y.empty() ? 0 : y[0].second);
}

// ---- --cho-anim ----

const std::vector<std::string> kAnimStateShape = {"1|Type|00b|", "1|Data|001|", "2|RangeMin|013|",
                                                  "2|RangeMax|013|"};   // a shipped 3.0 AnimState node
constexpr float kAnimRangeTolerance = 1e-4f;   // re-authored clips and events differ by more
constexpr size_t kShownAnimDiffs = 6, kShownInputsLeft = 3, kShownRoundTrips = 5;
constexpr uint16_t kNodeFieldLevel = 5;        // a DataNode's fields: SubNetwork 2, pool 3, node 4
const char* const kAnimFailures[] = {"twin: Input DIFFERS", "1.0 corpus: re-parse DIFFERS",
                                     "3.0 corpus: files DIFFER after the round trip",
                                     "1.0 corpus: AnimState node NOT in the 3.0 shape",
                                     "1.0 corpus: subnetwork with another header path changed"};

bool isTimed(const std::string& type) { return type == "ClipProcessor" || type == "EventList"; }

// A 1.0 file after time30 and anim30, and its 3.0 twin.
struct AnimTwin {
    const std::string& name;
    const oct::File& f;
    const oct::File& g;
    std::vector<SubNet> s, t;
};

// The twin's processor of type ty with pn's header path in the same-index SubNetwork k, or -1.
long twinProcessor(const AnimTwin& w, size_t k, size_t pn, const std::string& ty)
{
    if (k >= w.t.size()) return -1;
    for (size_t qn : w.t[k].processors) {
        if (childName(w.g, qn, "Type") != ty) continue;
        if (headerPath(w.g, w.t[k], qn) == headerPath(w.f, w.s[k], pn)) return (long)qn;
    }
    return -1;
}

// The larger RangeMin / RangeMax difference between two Inputs' Data.
float rangeError(const AnimTwin& w, long in, long in3)
{
    long d1 = child(w.f, in, "Data"), d3 = child(w.g, in3, "Data");
    float e = 0;
    for (const char* r : {"RangeMin", "RangeMax"})
        e = (std::max)(e, fabsf(floatAt(w.f, child(w.f, d1, r)) - floatAt(w.g, child(w.g, d3, r))));
    return e;
}

// Twin check of processor pn of SubNetwork k: its Input against the twin processor's.
void animTwinProcessor(const AnimTwin& w, size_t k, size_t pn, Tally& c)
{
    const std::string ty = childName(w.f, pn, "Type");
    if (!isTimed(ty)) return;
    const long in = inputNode(w.f, w.s[k], pn);
    if (in < 0) {
        ++c["twin: 1.0 processor without Input"];
        return;
    }
    const long q = twinProcessor(w, k, pn, ty);
    const long in3 = q < 0 ? -1 : inputNode(w.g, w.t[k], q);
    if (in3 < 0) {
        ++c["twin: no 3.0 processor with that header (re-authored)"];
        return;
    }
    const std::string p1 = headerPath(w.f, w.s[k], in), p3 = headerPath(w.g, w.t[k], in3);
    if (p1 == p3 && nodeDump(w.f, in, NodeDump::Values) == nodeDump(w.g, in3, NodeDump::Values)) {
        ++c["twin: Input identical to 3.0 (" + ty + ")"];
        return;
    }
    if (p1 == p3 && nodeDump(w.f, in, NodeDump::Shape) == nodeDump(w.g, in3, NodeDump::Shape)) {
        const bool within = rangeError(w, in, in3) < kAnimRangeTolerance;
        ++c[within ? "twin: Input same records, range within 1e-4"
                   : "twin: Input same records, range differs (re-authored clips/events)"];
        return;
    }
    if (const size_t n = ++c["twin: Input DIFFERS"]; n > kShownAnimDiffs) return;
    printf("differ %s sn %zu %s: '%s' vs '%s'\n", w.name.c_str(), k, ty.c_str(), p1.c_str(), p3.c_str());
    for (auto& l : nodeDump(w.f, in, NodeDump::Values)) printf("   10>30 %s\n", l.c_str());
    for (auto& l : nodeDump(w.g, in3, NodeDump::Values)) printf("   30    %s\n", l.c_str());
}

void animTwin(const std::string& n, oct::File& f, const oct::File& g, Tally& c)
{
    cho::time30(f);
    cho::anim30(f);
    const AnimTwin w{n, f, g, subnets(f), subnets(g)};
    for (size_t k = 0; k < w.s.size(); ++k)
        for (size_t pn : w.s[k].processors) animTwinProcessor(w, k, pn, c);
}

// (1) Twins. Returns the corpus indexes, built where the twins first walk them.
std::vector<SubIndex> animTwins(const Args& a, Tally& c)
{
    std::vector<SubIndex> idx;
    auto one = [&c](const std::string& n, const fs::path&, oct::File& f, oct::File& g) { animTwin(n, f, g, c); };
    for (const char* sub : kChoSubs) {
        idx.push_back({choIndex(a.argv[2], sub), choIndex(a.argv[3], sub)});
        forEachTupleTwin(idx.back().c10, idx.back().c30, one);
    }
    return idx;
}

// Header paths that changed other than 'Global.Time' -> 'AnimState'.
size_t otherPathChanges(const SubNet& now, const SubNet& was)
{
    size_t other = 0;
    for (size_t h = 0; h < now.paths.size() && h < was.paths.size(); ++h) {
        const bool renamed = was.paths[h] == "Global.Time" && now.paths[h] == "AnimState";
        other += now.paths[h] != was.paths[h] && !renamed;
    }
    return other;
}

// A timed processor's Input after anim30: an AnimState 'AnimState', or why it was left.
void tallyInputLeft(const oct::File& g, const SubNet& s, size_t pn, const fs::path& p, Tally& c)
{
    const std::string ty = childName(g, pn, "Type");
    if (!isTimed(ty)) return;
    const long in = inputNode(g, s, pn);
    const std::string pt = in < 0 ? "" : headerPath(g, s, in), it = in < 0 ? "" : childName(g, in, "Type");
    if (pt == "AnimState" && it == "AnimState") {
        ++c["1.0 corpus: " + ty + " Input -> AnimState 'AnimState'"];
        return;
    }
    const std::string why = in < 0           ? "no Input"
                            : it != "Float"  ? "type " + it
                            : pt != "Global.Time" ? "Float under another header"
                                                  : "Float 'Global.Time' SKIPPED";
    if (const size_t n = ++c["1.0 corpus: " + ty + " Input left: " + why]; n <= kShownInputsLeft)
        printf("left %s %s: %s '%s'\n", p.string().c_str(), ty.c_str(), it.c_str(), pt.c_str());
}

void animCorpusSubNet10(const oct::File& g, const SubNet& s, const SubNet& was, const fs::path& p, Tally& c)
{
    if (otherPathChanges(s, was) || s.paths.size() != was.paths.size())
        ++c["1.0 corpus: subnetwork with another header path changed"];
    for (size_t dn : s.dataNodes) {
        if (headerPath(g, s, dn) != "AnimState" || childName(g, dn, "Type") != "AnimState") continue;
        const bool shape = nodeDump(g, dn, NodeDump::Shape) == kAnimStateShape;
        ++c[std::string("1.0 corpus: AnimState node ") +
            (shape ? "in the shipped 3.0 record shape" : "NOT in the 3.0 shape")];
    }
    for (size_t pn : s.processors) tallyInputLeft(g, s, pn, p, c);
}

// (2) One 1.0 file: anim30 after time30, the re-parse, header paths, what each timed Input became.
void animCorpusFile10(const fs::path& p, Tally& c)
{
    std::string b = slurp(p);
    if (!isTuple(b)) return;
    oct::File f = parse(b);
    cho::time30(f);
    const auto before = subnets(f);
    int sns = 0, nodes = cho::anim30(f, &sns);
    c["1.0 corpus: nodes converted"] += nodes;
    c["1.0 corpus: subnetworks converted"] += sns;
    const std::string w = f.write();
    oct::File g = parse(w);
    if (g.write() != w) ++c["1.0 corpus: re-parse DIFFERS"];
    const auto S = subnets(g);
    for (size_t k = 0; k < S.size() && k < before.size(); ++k) animCorpusSubNet10(g, S[k], before[k], p, c);
}

// 'level|name|type|values' per record, names resolved: the reversal adds names to the table.
std::vector<std::string> canonRecords(const oct::File& f)
{
    std::vector<std::string> v;
    for (auto& r : f.recs) {
        std::string l = std::to_string(r.level) + "|" + f.name(r) + "|" + std::to_string(r.type) + "|";
        oct::Spec s = oct::spec(r.type);
        if (s.kind == oct::NAME || s.keyed) {
            for (auto& x : f.nameValues(r)) l += x + ",";
        }
        if (s.kind != oct::NAME) l += r.pay.substr(kNameIndexBytes * s.keyed);
        v.push_back(l);
    }
    return v;
}

// The AnimState DataNodes of s, tallying those not in 3.0's header or record shape.
std::vector<size_t> animStates30(const oct::File& g, const SubNet& s, Tally& c)
{
    std::vector<size_t> anims;
    for (size_t dn : s.dataNodes) {
        if (childName(g, dn, "Type") != "AnimState") continue;
        anims.push_back(dn);
        if (headerPath(g, s, dn) != "AnimState") ++c["3.0 corpus: AnimState under another header"];
        if (nodeDump(g, dn, NodeDump::Shape) != kAnimStateShape) ++c["3.0 corpus: AnimState with other records"];
    }
    return anims;
}

long subnetAbove(const oct::File& g, size_t node)
{
    for (size_t i = node; i-- > 0;)
        if (g.recs[i].level == 2) return (long)i;
    return -1;
}

// Header string 'AnimState' renamed 'Global.Time' in place; false if shared or 'Global.Time' exists.
bool renameAnimState(oct::File& g, size_t node)
{
    const long sn = subnetAbove(g, node);
    long hs = child(g, (size_t)sn, "HeaderStrings"), hsi = child(g, (size_t)sn, "HeaderStringIndices");
    auto strs = g.nameValues(g.recs[hs]);
    auto idx = g.ints(g.recs[hsi]);
    auto at = std::find(strs.begin(), strs.end(), "AnimState");
    int32_t s = (int32_t)(at - strs.begin());
    const bool missing = at == strs.end();
    const bool shared = std::count(idx.begin(), idx.end(), s) != 1;
    const bool hasGlobalTime = std::count(strs.begin(), strs.end(), "Global.Time") != 0;
    if (missing || shared || hasGlobalTime) return false;
    uint16_t gt = g.addName("Global.Time");
    memcpy(&g.recs[hs].pay[oct::spec(g.recs[hs].type).cw + kNameIndexBytes * (size_t)s], &gt, sizeof gt);
    return true;
}

// Each AnimState node of anims, last first, back in the 1.0 form {Type Float, Data 0.0}; their count.
int toFloatForm(oct::File& g, const std::vector<size_t>& anims)
{
    int nodes = 0;
    for (size_t q = anims.size(); q-- > 0;) {
        size_t dn = anims[q];
        std::vector<oct::Rec> t = {g.recs[child(g, dn, "Header")],
                                   g.nameScalar(kNodeFieldLevel, g.recs[child(g, dn, "Type")].name, "Float"),
                                   cho::floatRec(g, "Data", 0.f, kNodeFieldLevel)};
        g.recs.erase(g.recs.begin() + dn + 1, g.recs.begin() + g.blockEnd(dn));
        g.recs.insert(g.recs.begin() + dn + 1, t.begin(), t.end());
        ++nodes;
    }
    return nodes;
}

// (3) A shipped 3.0 file, AnimState nodes put in the 1.0 form, must come back from anim30.
void animRoundTrip30(const fs::path& p, Tally& c)
{
    std::string b = slurp(p);
    if (!isTuple(b) || !hasName(b, "AnimState")) return;
    oct::File g = parse(b);
    const auto want = canonRecords(g);
    int nodes = 0;
    const auto S = subnets(g);
    for (size_t k = S.size(); k-- > 0;) {   // last first: the edits keep earlier indices
        const std::vector<size_t> anims = animStates30(g, S[k], c);
        if (anims.empty()) continue;
        if (!renameAnimState(g, anims[0])) {
            ++c["3.0 corpus: file skipped (string 'AnimState' shared or 'Global.Time' present)"];
            return;
        }
        nodes += toFloatForm(g, anims);
    }
    int got = cho::anim30(g);
    bool same = got == nodes && canonRecords(g) == want;
    c["3.0 corpus: AnimState nodes regenerated"] += nodes;
    ++c[same ? "3.0 corpus: files identical after the round trip" : "3.0 corpus: files DIFFER after the round trip"];
    if (!same && c["3.0 corpus: files DIFFER after the round trip"] <= kShownRoundTrips)
        printf("round trip differs %s (%d of %d nodes)\n", p.string().c_str(), got, nodes);
}

// ---- --cho-scene ----

struct Placement {
    std::string name;   // NodeName
    int scene;          // SceneTreeNodeRef, kNoSceneRecord without the record
};
constexpr int kNoSceneRecord = -2;
constexpr size_t kShownScene30Diffs = 5, kShownSceneTwins = 4, kShownNoScene = 5;
const char* const kSceneFailures[] = {"3.0: files DIFFER", "1.0: re-parse DIFFERS",
                                      "1.0: placements still WITHOUT the record"};

std::vector<Placement> placements(const oct::File& f)
{
    std::vector<Placement> v;
    long pool = f.pool("AssociationPool");
    if (pool < 0) return v;
    for (size_t i = pool + 1, e = f.blockEnd(pool); i < e; ++i) {
        if (f.recs[i].level != 2 || childName(f, i, "Type") != "PlacementNode") continue;
        long s = child(f, i, "SceneTreeNodeRef");
        v.push_back({childName(f, i, "NodeName"), s < 0 ? kNoSceneRecord : cho::first(f, f.recs[s], kNoSceneRecord)});
    }
    return v;
}

std::vector<std::string> sceneNames(const oct::File& f)
{
    std::vector<std::string> v;
    long pool = f.pool("SceneTreeNodePool");
    if (pool < 0) return v;
    for (size_t i = pool + 1, e = f.blockEnd(pool); i < e; ++i)
        if (f.recs[i].level == 2) v.push_back(childName(f, i, "NodeName"));
    return v;
}

std::string sceneAt(const std::vector<std::string>& s, int k)
{
    return k >= 0 && (size_t)k < s.size() ? s[k] : std::string("(none)");
}

// Strips the SceneTreeNodeRef of every PlacementNode association; how many it removed.
size_t stripSceneRefs(oct::File& f, long pool)
{
    size_t stripped = 0;
    for (size_t i = f.blockEnd(pool); i-- > (size_t)pool + 1;) {
        if (f.recs[i].level != 2 || childName(f, i, "Type") != "PlacementNode") continue;
        long s = child(f, i, "SceneTreeNodeRef");
        if (s < 0) continue;
        f.recs.erase(f.recs.begin() + s);
        ++stripped;
    }
    return stripped;
}

// (1) A shipped 3.0 file, its placements' scene refs stripped, must come back byte-identical.
void scene30File(const fs::path& p, Tally& c)
{
    std::string b = slurp(p);
    if (!isTuple(b) || !hasName(b, "PlacementNode")) return;
    oct::File f = parse(b);
    long pool = f.pool("AssociationPool");
    if (pool < 0) return;
    const size_t stripped = stripSceneRefs(f, pool);
    if (!stripped) return;
    int got = cho::scene30(f);
    bool same = got == (int)stripped && f.write() == b;
    c["3.0: placements regenerated"] += stripped;
    ++c[same ? "3.0: files byte-identical" : "3.0: files DIFFER"];
    if (!same && c["3.0: files DIFFER"] <= kShownScene30Diffs) printf("3.0 differs %s\n", p.string().c_str());
}

// (2) The scene node scene30 names for each 1.0 placement against the one the 3.0 twin names.
void sceneTwin(const std::string& n, oct::File& f, const oct::File& g, Tally& c)
{
    cho::scene30(f);
    auto s10 = sceneNames(f), s30 = sceneNames(g);
    std::map<std::string, int> by30;
    for (auto& q : placements(g)) by30.emplace(q.name, q.scene);
    for (auto& q : placements(f)) {
        auto it = by30.find(q.name);
        if (it == by30.end()) {
            ++c["twin: placement NodeName not in the 3.0 twin"];
            continue;
        }
        bool same = sceneAt(s10, q.scene) == sceneAt(s30, it->second);
        ++c[std::string("twin: same scene node ") + (same ? "yes" : "NO") + (q.scene >= 0 ? " (set)" : " (-1)")];
        if (same) continue;
        if (c["twin: same scene node NO (set)"] + c["twin: same scene node NO (-1)"] <= kShownSceneTwins)
            printf("twin %s %s: '%s' vs '%s'\n", n.c_str(), q.name.c_str(), sceneAt(s10, q.scene).c_str(),
                   sceneAt(s30, it->second).c_str());
    }
}

// (3) A 1.0 file scene30 changed: the re-parse, and a scene node per placement.
void scene10File(const fs::path& p, Tally& c)
{
    std::string b = slurp(p);
    if (!isTuple(b)) return;
    oct::File f = parse(b);
    if (!cho::scene30(f)) return;
    const std::string w = f.write();
    oct::File g = parse(w);
    if (g.write() != w) ++c["1.0: re-parse DIFFERS"];
    ++c["1.0: files changed"];
    bool any = false;
    for (auto& q : placements(g)) {
        any |= q.scene >= 0;
        ++c[q.scene >= 0    ? "1.0: placements with a scene node"
            : q.scene == -1 ? "1.0: placements with -1"
                            : "1.0: placements still WITHOUT the record"];
    }
    if (any) return;
    if (const size_t n = ++c["1.0: files where no placement has a scene node"]; n <= kShownNoScene)
        printf("no scene node: %s\n", p.string().c_str());
}

